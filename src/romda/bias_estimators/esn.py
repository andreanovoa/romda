

import logging

import numpy as np
from romda.models import Model
from romda.models.data_driven import ESN_model
from romda.models.data_driven.rnns import ESN_STORE, ESNConfig, auto_load_or_create, find_matching_config
from romda.utils import save_to_pickle_file

from .aux import create_bias_training_dataset, load_bias_training_dataset
from .bias import Bias

logger = logging.getLogger(__name__)


class ESN_bias(Bias):
    r"""Echo-state-network bias estimator.

    An [`ESN_model`][romda.models.data_driven.rnns.esn.ESN_model] forecasts the model bias
    (and, if `biased_observations`, the innovations) in closed loop between analyses,
    and its open-loop linearization provides the Jacobian
    $\matr{J} = \mathrm{d}\vect{b}/\mathrm{d}\vect{q}$ used by the
    regularized bias-aware EnKF. The network is trained offline on synthetic
    innovation data generated by perturbing the low-order model (see
    [`create_bias_training_dataset`][romda.bias_estimators.aux.create_bias_training_dataset]);
    trained configurations are cached on disk and reloaded when the configuration
    hash matches (unless `force_retrain`).

    Parameters
    ----------
    rom : Model
        The (biased) low-order forecast model whose bias is estimated.
    reference_data : Observations or list of Observations, optional
        Reference data used to build the training dataset if no cached forecaster or
        dataset is found.
    **kwargs
        ESN hyperparameters (``N_units``, ``N_wash``, ``rho_range``, ...), training
        times (``t_train``, ``t_val``, ``t_test``), dataset options (``L``,
        ``augment_data``, ``correlation_based_training``) and `Bias` options.

    References
    ----------
    Nóvoa, Racca & Magri (2023). Inferring unknown unknowns: Regularized bias-aware
    ensemble Kalman filter. *Comput. Methods Appl. Mech. Eng.*, 418, 116502.
    [DOI: 10.1016/j.cma.2023.116502](https://doi.org/10.1016/j.cma.2023.116502).
    """

    biased_observations = True
    correlation_based_training = True
    augment_data = True

    def __init__(self,
                 rom: Model,
                 reference_data = None,
                 **kwargs):


        super().__init__(
                        innovation=kwargs.pop('innovation', np.zeros((rom.Nq,))),
                        dt=kwargs.pop('dt', rom.dt),
                        t=kwargs.pop('t', rom.t),
                        rom=rom,
                        reference_data=reference_data,
                        **kwargs)

    @property
    def initialize_bias_state(self):
        """Initial state of `N_ens` members, from reservoir states of the validation data."""
        return self.forecaster.initialize_from_val_data(N_ens=self.N_ens)


    @property
    def N_hidden(self):
        if not hasattr(self, 'forecaster'):
            return 0
        return self.forecaster.N_units


    def state_derivative(self):
        esn = self.forecaster #type: ESN_model
        state = self.current_state
        u_mean = np.mean(state[:self.N_dim], axis=-1, keepdims=True)
        r_mean = np.mean(state[-self.N_hidden:], axis=-1, keepdims=True)

        # Open-loop Jacobian, shape (N_dim, N_dim_in), against the network input
        esn_J = esn.Jacobian(open_loop_J=True, u_in=esn.outputs_to_inputs(u_mean), r_in=r_mean)

        # J = d b_{k+1} / d q = -d b_{k+1} / d i, with i = d - q: bias rows against the input
        # columns that carry the innovation, whether the input is [b; i] or i alone.
        innovation_cols = np.flatnonzero(np.isin(esn.observed_idx, self.observed_idx))
        return -esn_J[np.ix_(self.bias_idx, innovation_cols)]


    def init_forecaster(self,
                        training_data_filename: str | None = None,
                        **kwargs):
        """Load or train the `ESN_model` forecaster; `kwargs` must include `rom`."""
        cfg = self.config
        cfg.update(kwargs)

        cfg['N_dim'] = self.N_dim
        cfg['training_data_filename'] = training_data_filename
        cfg['dt'] = self.dt
        rom = kwargs.get('rom')

        assert rom is not None, "ROM object must be provided."

        # add training times if not provided in kwargs, with default values based on the ROM time scales
        t_test_default = 5 * rom.t_CR if kwargs.get('perform_test', True) else 0
        for key, default_value in zip(['t_train', 't_val', 't_test'], [rom.t_transient / 2, rom.t_CR, t_test_default]):
            if key not in cfg.keys():
                cfg[key] = kwargs.get(key, default_value)

        min_training_time = sum([cfg[key] for key in ['t_train', 't_val', 't_test']])
        self.minimum_training_steps = int(np.ceil(min_training_time / self.dt))

        self.forecaster = self.load_or_create_forecaster(**cfg)


    def load_or_create_forecaster(self, reference_data=None, rom=None, **kwargs) -> ESN_model:
        """Load the cached `ESN_model` of the configuration hash of `kwargs`, or train and cache one.

        Training needs `rom` and `reference_data`, from which the bias-training dataset is loaded
        (`training_data_filename`) or created; see `create_bias_training_dataset`.
        """
        # The model is saved under the QUERY hash: re-deriving the hash from the trained model would
        # use the t_train/t_val/t_test mutated by `_process_initialization_data`, so the next lookup
        # would miss forever.
        query_hash = ESNConfig.from_init_params(**kwargs).to_hash()
        if self.force_retrain or not find_matching_config(ESN_STORE, query_hash):
            if rom is None or reference_data is None:
                raise ValueError('Both rom and reference_data must be provided to create a new ESN_bias model')
            filename = kwargs.get('training_data_filename')
            train_data_dict = load_bias_training_dataset(filename=filename,
                                                         necessary_properties=self.config.copy(),
                                                         minimum_training_steps=self.minimum_training_steps,
                                                         augment_data_length=self.augment_data_length,
                                                         L=self.L,
                                                         expected_Ndim=self.N_dim)
            if train_data_dict is None:
                logger.debug('Creating the training data of the bias model')
                train_data_dict = create_bias_training_dataset(
                                        config=self.config,
                                        rom=rom,
                                        reference_data=reference_data,
                                        std_phi=kwargs.get('std_phi'),
                                        std_alpha=kwargs.get('std_alpha'),
                                        L=self.L,
                                        augment_data_length=self.augment_data_length,
                                        minimum_training_steps=self.minimum_training_steps,
                                        correlation_based_training=self.correlation_based_training,
                                        biased_observations=self.biased_observations,
                                    )
                if filename is not None:
                    save_to_pickle_file(filename, train_data_dict)
            kwargs.update(train_data_dict)

        return auto_load_or_create(query_hash=query_hash, force_create=self.force_retrain, **kwargs)

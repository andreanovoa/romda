"""Builders of trained echo state networks: from a physical model to its dataset and the network trained on it,
loaded from the ESN store when the store holds it (`auto_load_or_create`).

The store key covers the settings of the network, the split of the record and a digest of the training record
(`romda.utils.record_key`), so any change of the data or the settings trains, or loads, the matching network.
"""

import os

import numpy as np
from romda.models.data_driven.rnns.esn_config import auto_load_or_create
from romda.observations import esn_observed_idx
from romda.utils import create_dataset_from_model, noisy_copy, record_key, trajectory

__all__ = ['model_esn', 'parametric_esn', 'twin_data', 'network_summary']


def model_esn(model_class, truth, esn, cache: str = 'esn.pkl', plot_training: bool = False,
              measured: list | None = None, bayesian_update: bool = True, config_dir=None,
              force_create: bool | None = None, **overrides):
    """The dataset of a physical `Model` and the ESN trained on it, from the blocks of an experiment configuration
    (`romda.run.load_config`).

    `truth` is the ``truth`` block: the constructor parameters of the model (``params``), the noise level, the length
    of the record and its split in Lyapunov times (``noise_level``, ``num_lyap_times``, ``split_lyap``) and the seed of
    the record (``seed``, default 0); `Model.filename` keys the constructor parameters into the dataset file and,
    through it, the network hash, so dimensions never share a file. `esn` is the ``forecast.esn`` block, the settings of
    the network, which `overrides` update. Networks live under ``results/esn_configs/<hash>`` (or `config_dir`): the
    hash covers the settings, `observed_idx` (from `measured`/`bayesian_update`), the split, the dataset file name and a
    digest of the training record (see `record_key`), so any change, the content of the record included,
    trains-or-loads the matching network. ``cache=None`` (or ``force_create=True``) forces a retrain.
    Returns the network and the dataset dict extended with `dt`, `t_lyap`, `split`, `i_train`/`i_test`."""
    split_lyap = truth['split_lyap']
    data, data_file = create_dataset_from_model(model_class, noise_level=truth['noise_level'],
                                                num_lyap_times=truth['num_lyap_times'], seed=truth.get('seed', 0),
                                                **(truth.get('params') or {}))

    N_lyap = int(data['N_lyap'])
    dt = float(data['t'][1] - data['t'][0])
    split = [n * N_lyap for n in split_lyap]
    i_train, i_test = split[0], sum(split)
    data.update(N_lyap=N_lyap, dt=dt, t_lyap=N_lyap * dt, split=split,
                sigma_state=data['clean_data'].std(axis=0), i_train=i_train, i_test=i_test)

    N_dim = data['clean_data'].shape[1]
    params = {**esn, 'observed_idx': esn_observed_idx(measured, N_dim, bayesian_update)}
    params.update(overrides)

    # the dataset options (noise level, record length, seed) are in the file's name and
    # its content in the digest, so the config hash tells apart networks trained on
    # different data, a record regenerated by another environment included
    train_data = data['noisy_data'][i_train:i_test]
    net = auto_load_or_create(data=train_data, dt=dt,
                              N_train=split[1], N_val=split[2], N_test=split[3],
                              plot_training=plot_training,
                              training_data_filename=record_key(
                                  os.path.basename(str(data_file)), train_data),
                              force_create=(cache is None) if force_create is None else force_create,
                              **({} if config_dir is None else dict(config_dir=config_dir)),
                              **params)
    return net, data


def parametric_esn(model_class, train, esn, noise_level, values=None, dt=None, t_train=None, t_val=None,
                   t_test=None, cache='', measured=None, bayesian_update=True, model_kwargs: dict | None = None,
                   config_dir=None, force_create: bool | None = None, **overrides):
    """Cached parametric `ESN_model` of `model_class`, one trajectory per regime value, from the blocks of an experiment
    configuration.

    `train` is the ``forecast.train`` block: the swept constructor parameter (``param``), its name and label in the
    model (``est_name``, ``label``), the regime values, the time step and the lengths of the windows in Lyapunov times;
    `esn` is the ``forecast.esn`` block. `model_kwargs` are the constructor parameters of the training trajectories
    (``truth.params``: `Nx`, ...). The segments carry measurement noise, as the record of a single network
    (`model_esn`): `noise_level` times the standard deviation of each component of each segment, drawn by `noisy_copy`
    from one generator of seed 0, segment after segment. Returns the ESN, the `(L, Nt, N_dim)` noisy training segments
    and the `(1, L)` regime matrix for the estimator (`regimes=...`)."""
    t_lyap, tr = model_class.t_lyap, train
    values = tr['values'] if values is None else values
    dt = tr['dt'] if dt is None else dt
    t_train, t_val, t_test = (t or tr[f't_{k}_lyap'] * t_lyap for k, t in
                              zip(('train', 'val', 'test'), (t_train, t_val, t_test)))

    n_steps = int(round((t_train + t_val + t_test) / dt))
    rng = np.random.default_rng(0)
    segments = np.stack([noisy_copy(trajectory(model_class, seed=i, n_steps=n_steps, dt=dt,
                                               constructor_defaults=model_kwargs,
                                               **{tr['param']: v}), noise_level, rng)
                         for i, v in enumerate(values)])
    regimes = np.asarray(values, dtype=float)[np.newaxis, :]

    params = dict(esn, plot_training=True, perform_test=False,
                  observed_idx=esn_observed_idx(measured, segments.shape[-1], bayesian_update))
    params.update(overrides)

    # the regime set is this network's "dataset": encoding it, and a digest of the
    # noisy segments, in the hashed training-data name keys the store by it
    name = (f'parametric_{model_class.__name__}_N{segments.shape[-1]}_{tr["param"]}'
            + '-'.join(f'{v:g}' for v in values))
    # a raw O(10) parameter would swamp Win's dense parameter columns: by default the same Bayesian search that
    # tunes rho/sigma_in tunes its shift and scale too; the esn block may set its own (e.g.
    # optimize_parameter_normalization: data, the parameter normalized like the state before the search)
    param_norm = dict(optimize_parameter_normalization=True,
                      param_shift_range=(float(min(values)), float(max(values))), param_norm_range=(1., 20.))
    param_norm.update({k: params.pop(k) for k in list(param_norm) if k in params})
    esn = auto_load_or_create(
        data=segments, dt=dt, t_train=t_train, t_val=t_val, t_test=t_test,
        param_names=(tr['est_name'],), param_values=(float(np.mean(values)),),
        param_labels=(tr['label'],) if tr.get('label') else None,
        input_parameters=regimes,
        **param_norm,
        training_data_filename=record_key(name, segments),
        force_create=(cache is None) if force_create is None else force_create,
        **({} if config_dir is None else dict(config_dir=config_dir)),
        **params)
    return esn, segments, regimes


def twin_data(esn, data, n_spin_lyap=5, seed=0):
    """Perfect-model twin of the `model_esn` dataset: the held-out record becomes the
    closed-loop forecast of the network itself.

    The network is washed out on the held-out data, runs `n_spin_lyap` Lyapunov times in
    closed loop to reach its own attractor, and then generates a record as long as the
    held-out record. The noisy copy has the noise level of the dataset, relative to the
    standard deviation of each component, with a fixed `seed`. Because the forecast model
    of the filter is the model that generates the truth, the error that remains is the
    error of the filter, with no model error. Non-parametric networks only.

    The record is sampled at the step of the network, ``dt_ESN = upsample * dt``, not at
    the ``dt`` of the dataset, and `run_and_score` counts `Nt_obs` in steps of the record
    that it receives: pass ``Nt_obs // esn.upsample`` to keep the observation interval.
    Returns the keys that `run_and_score` reads (`clean_data`, `noisy_data`, `t`,
    `t_lyap`, ``i_test = 0``) and `dt`."""
    held_out = data['clean_data'][data['i_test']::esn.upsample]
    n_spin = int(round(n_spin_lyap * data['t_lyap'] / esn.dt_ESN))
    clean = esn.closed_loop(held_out, n_spin + len(held_out))[0][n_spin:]

    noise_level = (data['noisy_data'] - data['clean_data']).std(axis=0) / data['clean_data'].std(axis=0)
    noisy = noisy_copy(clean, noise_level, seed)
    return dict(clean_data=clean, noisy_data=noisy, t=np.arange(len(clean)) * esn.dt_ESN,
                dt=esn.dt_ESN, t_lyap=data['t_lyap'], i_test=0)


def network_summary(esn):
    """The training summary of `esn` (`EchoStateNetwork.training_summary`), or, for a network loaded from the
    store, which has none, its hyperparameters."""
    try:
        return esn.training_summary()
    except RuntimeError:
        names = ('rho', 'sigma_in', 'tikh') + (('sigma_param',) if getattr(esn, 'sigma_param', None) is not None
                                               else ())
        return 'loaded from the store | ' + ', '.join(f'{k}={float(np.ravel(getattr(esn, k))[0]):.3g}' for k in names)

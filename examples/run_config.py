"""Twin experiment on a physical model, described by one YAML config.

The truth is generated by the model itself and the ensemble forecasts with the
same model, estimating the parameters of the config online. Runs through
`romda.experiments.run_experiment` -- the same flow as

    python -m romda.experiments examples/<CONFIG>.yml [--seed N] [--set da.m=32]

plus the figures. CONFIG is a path under ``examples/``, without ``.yml``, e.g.

    python examples/run_config.py lorenz/lorenz96
    python examples/run_config.py thermoacoustics/rijke
    python examples/run_config.py thermoacoustics/vdp --members

The figures go to ``figs/`` in the folder of the config.
"""

import argparse
import os

from common import EXAMPLES_FOLDER, load_main_config, print_metrics, show_or_save_figs
from romda.experiments import run_experiment
from romda.models import physical

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('config', help="config path under examples/, e.g. 'thermoacoustics/rijke'")
    parser.add_argument('--members', action='store_true', help='plot the ensemble members')
    parser.add_argument('--save-figs', action='store_true',
                        help='save the figures to figs/ in the folder of the config instead of showing them')
    args = parser.parse_args()

    config = args.config.removesuffix('.yml')
    cfg = load_main_config(config)
    model = getattr(physical, cfg['truth']['model'])
    case = os.path.basename(config)

    filter_ens, truth, metrics = run_experiment(cfg)
    print_metrics(metrics, header=f'{case} twin experiment')

    filter_ens.visualize_history(truth=truth,
                                 plot_members=args.members,
                                 reference_t=getattr(model, 't_lyap', model.t_CR),
                                 reference_a=truth.true_parameters)
    show_or_save_figs(args.save_figs, prefix=case,
                      figs_folder=os.path.join(EXAMPLES_FOLDER, os.path.dirname(config), 'figs'))

"""Twin experiment on a physical model, described by one YAML config.

The truth is generated by the model itself and the ensemble forecasts with the
same model, estimating the parameters of the config online. Runs through
`romda.run.run_config` -- the same flow as

    python -m romda.run scripts/<CONFIG>.yml [--seed N] [--set da.m=32]

plus the figures. CONFIG is a path under ``scripts/``, without ``.yml``, e.g.

    python scripts/run_config.py examples/lorenz/lorenz96
    python scripts/run_config.py thermoacoustics/rijke
    python scripts/run_config.py thermoacoustics/vdp --members

The figures go to ``figs/`` in the folder of the config.
"""

import os

from common import SCRIPTS_FOLDER, load_main_config, main_parser, print_metrics, show_or_save_figs
from romda.run import resolve_model, run_config

if __name__ == '__main__':
    parser = main_parser(__doc__)
    parser.add_argument('config', help="config path under scripts/, e.g. 'thermoacoustics/rijke'")
    parser.add_argument('--members', action='store_true', help='plot the ensemble members')
    args = parser.parse_args()

    config = args.config.removesuffix('.yml')
    cfg = load_main_config(config)
    model = resolve_model(cfg['truth']['model'])
    case = os.path.basename(config)

    filter_ens, truth, metrics = run_config(cfg)
    print_metrics(metrics, header=f'{case} twin experiment')

    filter_ens.visualize_history(truth=truth,
                                 plot_members=args.members,
                                 reference_t=getattr(model, 't_lyap', model.t_CR),
                                 reference_a=truth.true_parameters)
    show_or_save_figs(args.save_figs, prefix=case,
                      figs_folder=os.path.join(SCRIPTS_FOLDER, os.path.dirname(config), 'figs'))
